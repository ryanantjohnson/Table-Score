const assert=require('node:assert/strict');
const {evaluate}=require(process.cwd()+'/native/dining-evidence.js');
const data=require(process.cwd()+'/data/dining-dishes.json').dishes;
const now=new Date('2026-11-17T18:00:00Z'),opts={now};
const cava=data.find(d=>d.id==='cava-falafel-crunch'),vegan=data.find(d=>d.id==='chipotle-rice-bean-bowl');
assert.equal(evaluate(cava,['Vegetarian'],opts).outcome,'supported');
assert.equal(evaluate(cava,['Vegetarian','Milk'],opts).outcome,'conflict');
assert.equal(evaluate(cava,['Vegan'],opts).outcome,'conflict');
assert.equal(evaluate(cava,['Peanut'],opts).outcome,'confirm');
assert.equal(evaluate(cava,['Halal'],opts).outcome,'unknown');
assert.equal(evaluate(cava,['Celiac / gluten'],opts).outcome,'unknown');
assert.equal(evaluate(cava,['Molluscs'],opts).outcome,'unknown');
assert.equal(evaluate(vegan,['Vegan','Vegetarian'],opts).outcome,'supported');
assert.equal(evaluate(vegan,['Vegan','Peanut'],opts).outcome,'confirm');
assert.equal(evaluate(vegan,['Vegan','Milk'],opts).outcome,'unknown');
assert.equal(evaluate(vegan,['Vegan','Halal'],opts).outcome,'unknown');
assert.equal(evaluate(vegan,['Vegan'],{...opts,notes:'Avoid garlic'}).outcome,'unknown');
assert.equal(evaluate(vegan,['Vegan'],{now:new Date('2026-12-18')}).outcome,'unknown');
assert.equal(evaluate(vegan,['Vegan'],{...opts,country:'GB'}).outcome,'unknown');
assert.equal(evaluate({...vegan,checked_on:'2026-11-18'},['Vegan'],opts).outcome,'unknown');
assert.equal(evaluate({...vegan,allergens:{Peanut:'contains'}},['Peanut'],{now:new Date('2027-01-01')}).outcome,'conflict');
assert.equal(evaluate(vegan,[],opts).outcome,'unfiltered');
assert.equal(evaluate({...vegan,diets:{Halal:true,Kosher:true,'Celiac / gluten':true}},['Halal'],opts).outcome,'unknown');
assert.equal(evaluate({...vegan,diets:{'Celiac / gluten':true}},['Celiac / gluten'],opts).outcome,'unknown');
console.log('PASS: multiple dietary needs, conflicts, unmarked allergens, shared kitchens, expired evidence, country scope and free-text restrictions.');
